#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""P7-08: produce the offline latency/staleness evidence file.

Generates a synthetic 90-frame chain (nominal timing plus planted spikes and a
planted stale reuse), then writes outputs/p7_latency/latency_budget_report.json.

Nothing is measured from hardware: the caller supplies timestamps, so the file is
stamped OFFLINE-SYNTHETIC and the pre-registered budgets are restated inside it.

Exit codes: 0 = evidence written; 1 = internal error.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.badminton_brain.timing.latency_budget import (  # noqa: E402
    MAX_SOURCE_FRAME_AGE_S,
    STAGE_BUDGET_S,
    StalenessGuard,
    StageTimestamps,
    StaleFrameRejected,
    latency_report,
)

OUT = ROOT / "outputs" / "p7_latency" / "latency_budget_report.json"
SEED = 20261021
N_FRAMES = 90


def build_frames(seed: int = SEED, n_frames: int = N_FRAMES):
    """Synthetic per-frame stage timestamps: nominal jitter in every stage."""
    rng = np.random.default_rng(seed)
    frames = []
    for index in range(n_frames):
        capture = round(index * 0.02, 9)  # 50 Hz
        capture_dur = float(rng.uniform(0.002, 0.006))
        detect = capture + capture_dur + float(rng.normal(0.022, 0.004))
        detect = max(detect, capture + 0.001)
        filter_ = detect + float(rng.normal(0.004, 0.0008))
        filter_ = max(filter_, detect + 1e-4)
        predict = filter_ + float(rng.normal(0.007, 0.0015))
        predict = max(predict, filter_ + 1e-4)
        command = predict + float(rng.normal(0.004, 0.0008))
        command = max(command, predict + 1e-4)
        frames.append(StageTimestamps(
            capture=capture, detect=round(detect, 9), filter=round(filter_, 9),
            predict=round(predict, 9), command=round(command, 9), frame_id=index))
    # planted spikes: one slow detector, one slow predictor
    slow = frames[30]
    frames[30] = StageTimestamps(capture=slow.capture, detect=slow.capture + 0.080,
                                 filter=slow.capture + 0.081,
                                 predict=slow.capture + 0.083,
                                 command=slow.capture + 0.087, frame_id=slow.frame_id)
    slow2 = frames[61]
    frames[61] = StageTimestamps(capture=slow2.capture, detect=slow2.detect,
                                 filter=slow2.filter,
                                 predict=slow2.predict + 0.030,
                                 command=slow2.predict + 0.034, frame_id=slow2.frame_id)
    return frames


def staleness_scenarios() -> dict:
    """Exercise the refusal policy: on-threshold, over-threshold, reuse, future."""
    guard = StalenessGuard()
    outcomes = {}

    def attempt(name, **kwargs):
        try:
            admission = guard.admit(**kwargs)
            outcomes[name] = {"result": "ADMITTED", **admission.to_json_dict()}
        except StaleFrameRejected as exc:
            outcomes[name] = {"result": "REFUSED", "reason": exc.reason,
                              "detail": exc.detail, **exc.admission.to_json_dict()}
        except Exception as exc:  # noqa: BLE001 - recorded, not hidden
            outcomes[name] = {"result": "ERROR", "detail": str(exc)}

    attempt("on_threshold_0.100s", prediction_id="p-on", frame_id=100,
            source_frame_timestamp_s=0.0, now_s=0.100)
    attempt("just_over_0.1001s", prediction_id="p-over", frame_id=101,
            source_frame_timestamp_s=0.0, now_s=0.1001)
    attempt("reuse_within_threshold", prediction_id="p-on", frame_id=100,
            source_frame_timestamp_s=0.0, now_s=0.050)
    attempt("future_source_frame", prediction_id="p-future", frame_id=102,
            source_frame_timestamp_s=5.0, now_s=4.9)
    return {
        "threshold_s": guard.threshold_s,
        "boundary": "age <= threshold admitted, age > threshold refused",
        "outcomes": outcomes,
        "report": guard.report(),
    }


def main() -> int:
    frames = build_frames()
    report = latency_report(frames)
    stale = staleness_scenarios()
    payload = {
        "schema": "badmin.p7.latency_evidence",
        "schema_version": 1,
        "evidence_class": "OFFLINE-SYNTHETIC",
        "claim": (
            "Timestamps were generated by this script. No camera, detector or robot "
            "ran; the numbers are budget ACCOUNTING on a synthetic chain, not measured "
            "hardware latency."
        ),
        "pre_registered": {
            "max_source_frame_age_s": MAX_SOURCE_FRAME_AGE_S,
            "stage_budget_s": STAGE_BUDGET_S,
            "registered_before_measurement": True,
        },
        "synthetic_chain": {
            "seed": SEED, "frames": len(frames),
            "nominal_hz": 50,
            "planted_spikes": {
                "frame_30": "detect stage 80 ms (budget 30 ms)",
                "frame_61": "predict stage +30 ms (budget 10 ms)",
            },
        },
        "latency": report,
        "staleness": stale,
        "unknowns": [
            "real D455 capture-to-timestamp latency",
            "real detector inference latency on the target CPU",
            "real EKF/predictor execution time",
            "actuation (CAN/network) latency",
            "closed-loop success rate",
        ],
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
                   encoding="utf-8")
    print("latency: e2e mean=%s s max=%s s over_budget_frames=%d"
          % (report["end_to_end"]["mean_s"], report["end_to_end"]["max_s"],
             report["end_to_end"]["over_budget_frames"]))
    for stage, block in report["per_stage"].items():
        print("  %-8s budget=%s max=%s status=%s over=%d"
              % (stage, block["budget_s"], block["max_s"], block["status"],
                 block["over_budget_frames"]))
    for name, outcome in stale["outcomes"].items():
        print("  staleness %-22s -> %s" % (name, outcome["result"]))
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
