"""Runtime Ultralytics dataset configuration built from audited manifests.

Why this module exists: Ultralytics reads an image list plus a dataset YAML, but in
this project what may be trained is decided by manifests whose rows carry a split.
Those two views can disagree, and nothing in Ultralytics would notice: one
fixed_core_test or challenge_test row that slips into a train list silently destroys
the independence of the frozen test set, which the whole regression protocol depends
on. This module is therefore the single place that converts manifests into the
runtime configuration, and it refuses to write one at all when a held-out sample --
or a sample whose split it cannot recognise -- is present.

Two kinds of source are accepted for each pool, because both are legitimate ways to
describe a training pool, and both are guarded the same way:

    * an audited manifest CSV with `file` and `split` columns, one row per sample;
    * an existing image list file, one image path per line.

Spec: docs/superpowers/specs/02_BASELINE_TRAINING_SPEC.md (section 2: nc=1, class 0
"shuttlecock") and 00_SHUTTLE_DETECTION_MASTER_SPEC.md (3.10: FIXED_CORE_TEST and
CHALLENGE_TEST are never trained on directly).

Generation host: the image lists and the dataset YAML contain absolute image paths of
the machine that generated them, so a generated configuration is only valid there. It
must therefore be generated on the training host itself, not on a workstation and
copied over, and not from a checkout mounted at a different path. The files are also
written with explicit LF line endings: the training host is Linux, where a trailing
carriage return would turn every image path into a path that does not exist.

Run this module's tests with:
    python tests/perception/shuttle_detection/test_ultralytics_dataset.py -v
"""
from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any, Iterable, Sequence

import yaml

from .contracts import SPLITS


def _canonical(path: Path) -> Path:
    """Absolute and normalised, WITHOUT following symlinks.

    Path.resolve() walks every path component with lstat/readlink. On the training host the
    project tree lives on a FUSE mount (/home/T7 is fuseblk), where that call HANGS rather than
    returning slowly: a 673-row manifest stalled the trainer indefinitely with the process
    blocked in posixpath._joinrealpath and consuming zero CPU, which looked like a dead GPU job
    until faulthandler was enabled and SIGABRT dumped the stack.

    abspath normalises "." and ".." and makes the path absolute, which is all the dataset
    configuration needs - Ultralytics opens these paths directly and reads through symlinks. The
    generated lists still contain absolute paths of the host that generated them, which the
    module docstring already requires.
    """
    return Path(os.path.abspath(str(path)))
from .dataset_audit import ManifestError, ManifestMissingError, read_manifest

# The detection task. Spec section 2 fixes both values, so they are not configurable.
NC = 1
CLASS_NAMES: dict[int, str] = {0: "shuttlecock"}

# Files written into the output directory.
DATASET_YAML_NAME = "dataset.yaml"
IMAGE_LIST_NAMES: dict[str, str] = {"train": "train.txt", "val": "val.txt"}

# Pools that may appear in a training configuration, and the pools that may not.
TRAINABLE_SPLITS: tuple[str, ...] = ("train", "val")
HELD_OUT_SPLITS: tuple[str, ...] = ("fixed_core_test", "challenge_test")

# Directories searched for a manifest row image, in order. The first entry is the
# frozen P4-A layout (<root>/<split>/images/<file>).
IMAGE_SUBDIR = "images"

HEADER = (
    "# Generated by src/perception/shuttle_detection/ultralytics_dataset.py.",
    "# Do not edit: rebuild it from the manifests instead.",
)


class DatasetConfigError(RuntimeError):
    """The runtime dataset configuration cannot be built as requested."""


class SplitGuardError(DatasetConfigError):
    """A source carries a split this module refuses to train on."""


class ForbiddenSplitError(SplitGuardError):
    """A fixed_core_test or challenge_test sample was offered for training."""


class UnknownSplitError(SplitGuardError):
    """A split value outside the project vocabulary cannot be assumed trainable."""


class SplitRoleMismatchError(SplitGuardError):
    """A pool contains samples of the other trainable split."""


def canonical_split(value: Any) -> str:
    """Fold a raw split value onto a comparable key.

    Case, surrounding whitespace and the choice of separator are presentation, not
    meaning: " FIXED-CORE TEST " and "fixed_core_test" name the same pool, and the
    guard must not be defeatable by respelling it.
    """
    text = "" if value is None else str(value)
    return re.sub(r"[^a-z0-9]+", "_", text.strip().lower()).strip("_")


def held_out_reason(value: Any) -> str | None:
    """Explain why a split value names a held-out pool, or return None.

    The exact names of spec section 3.10 are matched first; the trailing `_test`
    and `challenge` spellings are matched as well, because a pool that is not
    trainable under a slightly different name is still not trainable.
    """
    key = canonical_split(value)
    if not key:
        return None
    compact = key.replace("_", "")
    if key in HELD_OUT_SPLITS or compact in ("fixedcoretest", "challengetest"):
        return "held-out pool (fixed_core_test / challenge_test never enter training)"
    if key == "test" or key.endswith("_test") or "challenge" in key:
        return "held-out pool spelled as " + repr(value)
    return None


def _first_non_empty_line(path: Path) -> str:
    with path.open("r", encoding="utf-8-sig") as handle:
        for line in handle:
            if line.strip():
                return line
    return ""


def _looks_like_manifest(path: Path) -> bool:
    """A manifest is recognised by a header row carrying a `file` column."""
    header = _first_non_empty_line(path)
    if not header:
        return False
    tokens = [token.strip().strip(chr(34)).strip(chr(39)).lower() for token in header.split(",")]
    return "file" in tokens


def _check_split(sample_id: str, raw_split: str, role: str, source: Path) -> str:
    """Validate one row split and return its canonical trainable value."""
    reason = held_out_reason(raw_split)
    if reason is not None:
        raise ForbiddenSplitError(
            "refusing to build a "
            + role
            + " dataset from "
            + repr(sample_id)
            + " in "
            + source.name
            + ": split="
            + repr(raw_split)
            + " is a "
            + reason,
        )
    key = canonical_split(raw_split)
    if key not in SPLITS:
        raise UnknownSplitError(
            "refusing to build a "
            + role
            + " dataset from "
            + repr(sample_id)
            + " in "
            + source.name
            + ": unknown split="
            + repr(raw_split)
            + "; known splits are "
            + ", ".join(SPLITS),
        )
    if key != role:
        raise SplitRoleMismatchError(
            "the "
            + role
            + " pool contains a "
            + key
            + " sample "
            + repr(sample_id)
            + " in "
            + source.name,
        )
    return key


def _resolve_image(manifest_dir: Path, data_root: Path | None, split: str, file_name: str) -> Path:
    """Locate a manifest row image without inventing a path that does not exist.

    The frozen P4-A layout is tried first, then the manifest directory itself, then
    the data root. When nothing matches, the canonical layout is returned so the
    written list still names where the image was expected; existence is the auditing
    step's job, not this one's.
    """
    name = Path(str(file_name).strip())
    if name.is_absolute():
        return _canonical(name)
    candidates = [
        manifest_dir / split / IMAGE_SUBDIR / name,
        manifest_dir / split / name,
        manifest_dir / name,
    ]
    if data_root is not None:
        candidates.extend(
            [
                data_root / split / IMAGE_SUBDIR / name,
                data_root / split / name,
                data_root / IMAGE_SUBDIR / name,
                data_root / name,
            ]
        )
    for candidate in candidates:
        if candidate.is_file():
            return _canonical(candidate)
    return _canonical(manifest_dir / split / IMAGE_SUBDIR / name)


def _lines_from_manifest(path: Path, role: str, data_root: Path | None) -> list[str]:
    rows, columns = read_manifest(path)
    present = {str(column).strip() for column in columns}
    if "file" not in present or "split" not in present:
        raise ManifestError(
            "manifest must have a file and a split column to be trainable: " + str(path)
        )
    lines: list[str] = []
    for row in rows:
        file_name = str(row.get("file", "") or "").strip()
        sample_id = Path(file_name).stem if file_name else ""
        if not file_name:
            raise DatasetConfigError("manifest row without a file value in " + path.name)
        split = _check_split(sample_id, str(row.get("split", "") or ""), role, path)
        lines.append(str(_resolve_image(path.parent, data_root, split, file_name)))
    return lines


def _lines_from_image_list(path: Path, role: str) -> list[str]:
    lines: list[str] = []
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        text = line.strip()
        if not text or text.startswith("#"):
            continue
        candidate = Path(text)
        if not candidate.is_absolute():
            candidate = path.parent / candidate
        lines.append(str(_canonical(candidate)))
    return lines


def _assert_no_held_out_paths(role: str, lines: Sequence[str], source: Path) -> None:
    """Refuse an image whose path already sits inside a held-out pool directory.

    A manifest can claim split=train while its file physically lives under
    challenge_test; the split column alone would not catch that, the path does.
    """
    for line in lines:
        for part in Path(line).parts:
            reason = held_out_reason(part)
            if reason is not None:
                raise ForbiddenSplitError(
                    "refusing to build a "
                    + role
                    + " dataset from "
                    + source.name
                    + ": image "
                    + line
                    + " lives in a "
                    + reason,
                )


def _dedupe(lines: Iterable[str]) -> list[str]:
    """Keep the file order while dropping repeated images from one pool."""
    seen: set[str] = set()
    unique: list[str] = []
    for line in lines:
        if line in seen:
            continue
        seen.add(line)
        unique.append(line)
    return unique


def _write_text_lf(path: Path, text: str) -> None:
    """Write text with LF endings regardless of the platform.

    Without an explicit newline argument, Python text mode translates every line
    ending to os.linesep and writes CRLF on Windows. Ultralytics on the remote Linux
    host would then read every image path with a trailing carriage return and fail to
    find the image, so the newline is pinned instead of inherited from the platform.
    """
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def _pool_lines(source: Path | str, role: str, data_root: Path | None) -> list[str]:
    path = Path(source)
    if not path.is_file():
        raise ManifestMissingError("manifest not found: " + str(path))
    if _looks_like_manifest(path):
        lines = _lines_from_manifest(path, role, data_root)
    else:
        lines = _lines_from_image_list(path, role)
    _assert_no_held_out_paths(role, lines, path)
    if not lines:
        raise DatasetConfigError("the " + role + " pool is empty: " + str(path))
    return _dedupe(lines)


def write_dataset_yaml(
    output_dir: Path | str,
    train_list_path: Path | str,
    val_list_path: Path | str,
    *,
    data_root: Path | str | None = None,
    dataset_name: str = DATASET_YAML_NAME,
) -> Path:
    """Write the single-class Ultralytics dataset configuration and return its path.

    train_list_path / val_list_path are the sources of the two pools: an audited
    manifest CSV, or an already built image list. Each is converted into an image
    list file inside output_dir and named by IMAGE_LIST_NAMES; the YAML references
    those written files by absolute path, so it does not depend on the working
    directory Ultralytics happens to be launched from.

    Raises ForbiddenSplitError when a fixed_core_test or challenge_test sample is
    offered -- as a manifest row or as an image living in such a directory --
    UnknownSplitError for a split outside the project vocabulary, and
    SplitRoleMismatchError when a pool carries samples of the other trainable split.
    Nothing is written when any of those checks fails.
    """
    output = Path(output_dir)
    root = None if data_root is None else Path(data_root)

    # Both pools are read and validated before anything is written, so a refusal
    # never leaves a half-built configuration behind.
    lines_by_pool = {
        role: _pool_lines(source, role, root)
        for role, source in (
            (TRAINABLE_SPLITS[0], train_list_path),
            (TRAINABLE_SPLITS[1], val_list_path),
        )
    }

    output.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}
    for role, lines in lines_by_pool.items():
        list_path = output / IMAGE_LIST_NAMES[role]
        _write_text_lf(list_path, "".join(line + "\n" for line in lines))
        written[role] = list_path

    document = {
        "path": str(_canonical(root if root is not None else output)),
        "train": str(_canonical(written[TRAINABLE_SPLITS[0]])),
        "val": str(_canonical(written[TRAINABLE_SPLITS[1]])),
        "nc": NC,
        "names": dict(CLASS_NAMES),
    }
    dataset_yaml = output / dataset_name
    _write_text_lf(
        dataset_yaml,
        "".join(line + "\n" for line in HEADER)
        + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, default_flow_style=False),
    )
    return dataset_yaml


def build_dataset_yaml(
    train_manifest: Path | str,
    val_manifest: Path | str,
    output_dir: Path | str,
    *,
    data_root: Path | str | None = None,
) -> Path:
    """Plan-style alias for write_dataset_yaml, with the output directory last."""
    return write_dataset_yaml(
        output_dir, train_manifest, val_manifest, data_root=data_root
    )
