def schema_source() -> str:
    """Which validator enforces the detection payload contract in this process."""
    return SCHEMA_SOURCE


class EvalSchemaError(ValueError):
    """Input data violates the evaluation protocol; nothing is scored."""

    def __init__(self, problems: Sequence[Tuple[str, str, str]]):
        self.problems = list(problems)
        lines = [f"{code}: {where}: {detail}" for code, where, detail in self.problems]
        super().__init__("input rejected by the P7-02 schema validation:\n" + "\n".join(lines))


def _finite(value: Any, where: str, key: str, problems: List[Tuple[str, str, str]]) -> Optional[float]:
    if isinstance(value, bool) or value is None:
        problems.append(("BAD_NUMBER", where, f"{key} must be a real number, got {value!r}"))
        return None
    try:
        out = float(value)
    except (TypeError, ValueError):
        problems.append(("BAD_NUMBER", where, f"{key} must be a real number, got {value!r}"))
        return None
    if not math.isfinite(out):
        problems.append(("BAD_NUMBER", where, f"{key} must be finite, got {out!r}"))
        return None
    return out


def _bbox(value: Any, where: str, problems: List[Tuple[str, str, str]]) -> Optional[np.ndarray]:
    try:
        arr = np.asarray(value, dtype=float)
    except (TypeError, ValueError):
        problems.append(("BAD_BBOX", where, f"bbox must be four numbers, got {value!r}"))
        return None
    if arr.shape != (4,):
        problems.append(("BAD_BBOX", where, f"bbox must have shape (4,), got {arr.shape}"))
        return None
    if not np.all(np.isfinite(arr)):
        problems.append(("BAD_NUMBER", where, "bbox contains NaN/Inf"))
        return None
    x1, y1, x2, y2 = (float(v) for v in arr)
    if not (x2 > x1 and y2 > y1):
        problems.append(("BAD_BBOX", where, f"bbox must satisfy x2>x1 and y2>y1, got {arr.tolist()}"))
        return None
    if x1 < 0.0 or y1 < 0.0:
        problems.append(("BAD_BBOX", where, f"bbox has negative coordinates: {arr.tolist()}"))
        return None
    return arr


def _check_pixel_payload(payload: Mapping[str, Any], where: str,
                         problems: List[Tuple[str, str, str]]) -> None:
    """Apply the same three pixel gates as the P7-04 schema (no metric leakage)."""
    metric = [key for key in _METRIC_KEYS if key in payload]
    if metric:
        problems.append(("UNIT_CONFUSION", where,
                         f"metric key(s) {metric} in a pixel payload"))
    covariance = payload.get("pixel_covariance")
    if covariance is None:
        return
    if _p7_validate_detection_payload is not None:
        probe = {
            "schema": "badmin.shuttle_detection.observation", "schema_version": 1,
            "units": {"bbox_xyxy_px": "px", "pixel_covariance": "px^2",
                      "timestamp_s": "s", "confidence": "1"},
            "timestamp_s": payload.get("timestamp_s", 0.0),
            "frame_id": 0, "camera_id": payload.get("camera_id", "unknown"),
            "image_size": payload.get("image_size", {"width_px": 1280, "height_px": 720}),
            "bbox_xyxy_px": payload.get("bbox_xyxy_px"),
            "confidence": payload.get("confidence"),
            "pixel_covariance": covariance,
            "validity": {"detected": True, "in_image": True, "confidence_ok": True,
                         "covariance_ok": True, "timestamp_ok": True,
                         "reject_reason": "NONE"},
        }
        try:
            _p7_validate_detection_payload(probe)
        except Exception as exc:  # noqa: BLE001 - surfaced as a schema problem
            problems.append(("UNIT_CONFUSION", where, f"P7-04 validator rejected it: {exc}"))
        return
    arr = np.asarray(covariance, dtype=float)
    if arr.shape != (2, 2) or not np.all(np.isfinite(arr)):
        problems.append(("BAD_NUMBER", where, "pixel_covariance must be a finite 2x2"))
        return
    if not np.allclose(arr, arr.T, atol=1e-9):
        problems.append(("BAD_NUMBER", where, "pixel_covariance must be symmetric"))
        return
    if float(np.min(np.diag(arr))) < FALLBACK_MIN_PIXEL_VARIANCE_PX2:
        problems.append(("UNIT_CONFUSION", where,
                         "pixel_covariance diagonal below the declared pixel floor "
                         f"{FALLBACK_MIN_PIXEL_VARIANCE_PX2} px^2 (metre^2 covariance?)"))


def bucket_for_size(size_px: Any) -> str:
    """P7-02 bucket for one size in pixels (half-open [lo, hi))."""
    try:
        value = float(size_px)
    except (TypeError, ValueError):
        return UNKNOWN_BUCKET
    if not math.isfinite(value) or value <= 0.0:
        return UNKNOWN_BUCKET
    if value < SIZE_BUCKET_EDGES[0][1]:
        return SMALLEST_BUCKET
    for name, lo, hi in SIZE_BUCKET_EDGES:
        if lo <= value < hi:
            return name
    return SIZE_BUCKET_EDGES[-1][0]


@dataclass(frozen=True)
class GtObject:
    bbox_xyxy_px: np.ndarray
    size_px: float

    @property
    def bucket(self) -> str:
        return bucket_for_size(self.size_px)


@dataclass
class GtFrame:
    frame_key: str
    split: str
    labeled: bool
    objects: List[GtObject]
    camera_id: Optional[str] = None
    image_size: Optional[Dict[str, int]] = None
    timestamp_s: Optional[float] = None


@dataclass
class Detection:
    frame_key: str
    bbox_xyxy_px: np.ndarray
    confidence: float
    latency_ms: Optional[float] = None
    bucket: str = UNKNOWN_BUCKET
    image_size: Optional[Dict[str, int]] = None
    camera_id: Optional[str] = None
    timestamp_s: Optional[float] = None


def read_jsonl(path: Path) -> List[Dict[str, Any]]:
    """Read a JSONL file into dicts; a malformed line is a schema error, not a crash."""
    records: List[Dict[str, Any]] = []
    problems: List[Tuple[str, str, str]] = []
    with Path(path).open("r", encoding="utf-8-sig") as handle:
        for line_no, line in enumerate(handle, start=1):
            text = line.strip()
            if not text:
                continue
            try:
                payload = json.loads(text)
            except json.JSONDecodeError as exc:
                problems.append((str(("BAD_SCHEMA")), f"{path}:{line_no}", f"not JSON: {exc}"))
                continue
            if not isinstance(payload, dict):
                problems.append(("BAD_SCHEMA", f"{path}:{line_no}",
                                 f"expected an object, got {type(payload).__name__}"))
                continue
            records.append(payload)
    if problems:
        raise EvalSchemaError(problems)
    return records


def parse_ground_truth(records: Sequence[Mapping[str, Any]],
                       *, strict: bool = True) -> Dict[str, GtFrame]:
    """Validate ground-truth records into frames keyed by frame_key."""
    problems: List[Tuple[str, str, str]] = []
    frames: Dict[str, GtFrame] = {}
    for index, payload in enumerate(records):
        where = "ground_truth[" + str(index) + "]"
        if payload.get("schema") != GT_SCHEMA_ID:
            problems.append(("BAD_SCHEMA", where,
                             f"schema must be {GT_SCHEMA_ID!r}, got {payload.get('schema')!r}"))
            continue
        if payload.get("schema_version") != EVAL_SCHEMA_VERSION:
            problems.append(("BAD_SCHEMA", where,
                             f"schema_version must be {EVAL_SCHEMA_VERSION}, got "
                             f"{payload.get('schema_version')!r}"))
            continue
        if strict:
            unknown = [key for key in payload if key not in _GT_KEYS]
            if unknown:
                problems.append(("UNKNOWN_KEY", where, f"unknown key(s) {unknown}"))
        for key in ("frame_key", "split", "labeled", "objects"):
            if key not in payload:
                problems.append(("MISSING_KEY", where, f"missing required key {key!r}"))
        frame_key = payload.get("frame_key")
        if not isinstance(frame_key, str) or not frame_key.strip():
            problems.append(("BAD_SCHEMA", where, "frame_key must be a non-empty string"))
            continue
        if payload.get("labeled") is not True:
            problems.append(("UNLABELED_FRAME", where,
                             f"labeled must be exactly true, got {payload.get('labeled')!r}: "
                             "an unlabeled frame cannot contribute a metric"))
            continue
        if frame_key in frames:
            problems.append(("DUPLICATE_FRAME", where, f"duplicate frame_key {frame_key!r}"))
            continue
        objects_payload = payload.get("objects")
        if not isinstance(objects_payload, list):
            problems.append(("BAD_SCHEMA", where, "objects must be a list ([] is a hard negative)"))
            continue
        objects: List[GtObject] = []
        for obj_index, obj in enumerate(objects_payload):
            obj_where = where + f".objects[{obj_index}]"
            if not isinstance(obj, Mapping):
                problems.append(("BAD_SCHEMA", obj_where, "object must be a mapping"))
                continue
            if strict:
                unknown = [key for key in obj if key not in _OBJECT_KEYS]
                if unknown:
                    problems.append(("UNKNOWN_KEY", obj_where, f"unknown key(s) {unknown}"))
            bbox = _bbox(obj.get("bbox_xyxy_px"), obj_where, problems)
            if bbox is None:
                continue
            extent = bbox[2:] - bbox[:2]
            declared = obj.get("size_px")
            if declared is None:
                size = float(math.sqrt(float(extent[0]) * float(extent[1])))
            else:
                size = _finite(declared, obj_where, "size_px", problems) or 0.0
            objects.append(GtObject(bbox_xyxy_px=bbox, size_px=size))
        image_size = payload.get("image_size")
        if image_size is not None:
            if not isinstance(image_size, Mapping) or not all(
                    isinstance(image_size.get(k), int) for k in ("width_px", "height_px")):
                problems.append(("BAD_SCHEMA", where,
                                 "image_size must be {width_px:int, height_px:int}"))
                image_size = None
        timestamp = payload.get("timestamp_s")
        timestamp_value = _finite(timestamp, where, "timestamp_s", problems) if timestamp is not None else None
        frames[frame_key] = GtFrame(
            frame_key=frame_key, split=str(payload.get("split")), labeled=True,
            objects=objects, camera_id=payload.get("camera_id"),
            image_size=dict(image_size) if image_size else None,
            timestamp_s=timestamp_value,
        )
    if problems:
        raise EvalSchemaError(problems)
    return frames


def parse_predictions(records: Sequence[Mapping[str, Any]], *, strict: bool = True) -> List[Detection]:
    """Validate prediction records into detections (no GT knowledge here)."""
    problems: List[Tuple[str, str, str]] = []
    detections: List[Detection] = []
    for index, payload in enumerate(records):
        where = "predictions[" + str(index) + "]"
        if payload.get("schema") != PRED_SCHEMA_ID:
            problems.append(("BAD_SCHEMA", where,
                             f"schema must be {PRED_SCHEMA_ID!r}, got {payload.get('schema')!r}"))
            continue
        if payload.get("schema_version") != EVAL_SCHEMA_VERSION:
            problems.append(("BAD_SCHEMA", where,
                             f"schema_version must be {EVAL_SCHEMA_VERSION}, got "
                             f"{payload.get('schema_version')!r}"))
            continue
        if strict:
            unknown = [key for key in payload if key not in _PRED_KEYS]
            if unknown:
                problems.append(("UNKNOWN_KEY", where, f"unknown key(s) {unknown}"))
        for key in ("frame_key", "bbox_xyxy_px", "confidence"):
            if key not in payload:
                problems.append(("MISSING_KEY", where, f"missing required key {key!r}"))
        frame_key = payload.get("frame_key")
        if not isinstance(frame_key, str) or not frame_key.strip():
            problems.append(("BAD_SCHEMA", where, "frame_key must be a non-empty string"))
            continue
        bbox = _bbox(payload.get("bbox_xyxy_px"), where, problems)
        confidence = _finite(payload.get("confidence"), where, "confidence", problems)
        if confidence is not None and not (0.0 <= confidence <= 1.0):
            problems.append(("BAD_NUMBER", where, f"confidence must be in [0,1], got {confidence}"))
        latency = payload.get("latency_ms")
        latency_value: Optional[float] = None
        if latency is not None:
            latency_value = _finite(latency, where, "latency_ms", problems)
            if latency_value is not None and latency_value < 0.0:
                problems.append(("BAD_NUMBER", where, f"latency_ms must be >= 0, got {latency_value}"))
        _check_pixel_payload(payload, where, problems)
        image_size = payload.get("image_size")
        if image_size is not None and (not isinstance(image_size, Mapping) or not all(
                isinstance(image_size.get(k), int) for k in ("width_px", "height_px"))):
            problems.append(("BAD_SCHEMA", where,
                             "image_size must be {width_px:int, height_px:int}"))
            image_size = None
        timestamp = payload.get("timestamp_s")
        timestamp_value = _finite(timestamp, where, "timestamp_s", problems) if timestamp is not None else None
        if bbox is None or confidence is None:
            continue
        extent = bbox[2:] - bbox[:2]
        detections.append(Detection(
            frame_key=frame_key, bbox_xyxy_px=bbox, confidence=confidence,
            latency_ms=latency_value,
            bucket=bucket_for_size(math.sqrt(float(extent[0]) * float(extent[1]))),
            image_size=dict(image_size) if image_size else None,
            camera_id=payload.get("camera_id"), timestamp_s=timestamp_value,
        ))
    if problems:
        raise EvalSchemaError(problems)
    return detections


def validate_inputs(gt: Mapping[str, GtFrame], detections: Sequence[Detection],
                    *, strict: bool = True) -> Dict[str, int]:
    """Cross-check predictions against the ground truth before any metric runs.

    This is the gate the task requires: a prediction for a frame that is not in
    the labeled ground truth, or whose camera/image size disagrees with it, is
    REJECTED - scoring it would silently mix datasets.
    """
    problems: List[Tuple[str, str, str]] = []
    rejected_frames = 0
    for index, det in enumerate(detections):
        where = f"predictions[{index}].frame_key={det.frame_key!r}"
        if det.frame_key not in gt:
            problems.append(("UNKNOWN_FRAME", where,
                             "frame_key is not present in the labeled ground truth"))
            rejected_frames += 1
            continue
        frame = gt[det.frame_key]
        if not frame.labeled:
            problems.append(("UNLABELED_FRAME", where, "the ground-truth frame is not labeled"))
            rejected_frames += 1
            continue
        if strict:
            if det.camera_id is not None and frame.camera_id is not None \
                    and det.camera_id != frame.camera_id:
                problems.append(("MISMATCHED_FRAME", where,
                                 f"camera_id {det.camera_id!r} != ground truth {frame.camera_id!r}"))
                rejected_frames += 1
            if det.image_size and frame.image_size and det.image_size != frame.image_size:
                problems.append(("MISMATCHED_FRAME", where,
                                 f"image_size {det.image_size} != ground truth {frame.image_size}"))
                rejected_frames += 1
    if problems:
        raise EvalSchemaError(problems)
    counts = {
        "gt_frames": len(gt),
        "gt_objects": sum(len(frame.objects) for frame in gt.values()),
        "gt_negative_frames": sum(1 for frame in gt.values() if not frame.objects),
        "predictions": len(detections),
        "predicted_frames": len({det.frame_key for det in detections}),
        "rejected_frames": rejected_frames,
    }
    return counts


def iou_xyxy(a: np.ndarray, b: np.ndarray) -> float:
    """IoU of two (x1, y1, x2, y2) boxes."""
    x1 = max(float(a[0]), float(b[0]))
    y1 = max(float(a[1]), float(b[1]))
    x2 = min(float(a[2]), float(b[2]))
    y2 = min(float(a[3]), float(b[3]))
    inter_w = x2 - x1
    inter_h = y2 - y1
    if inter_w <= 0.0 or inter_h <= 0.0:
        return 0.0
    inter = inter_w * inter_h
    area_a = (float(a[2]) - float(a[0])) * (float(a[3]) - float(a[1]))
    area_b = (float(b[2]) - float(b[0])) * (float(b[3]) - float(b[1]))
    union = area_a + area_b - inter
    return float(inter / union) if union > 0.0 else 0.0


def centre_distance(a: np.ndarray, b: np.ndarray) -> float:
    """Euclidean distance between bbox centres, in pixels."""
    ca = np.array([(a[0] + a[2]) / 2.0, (a[1] + a[3]) / 2.0], dtype=float)
    cb = np.array([(b[0] + b[2]) / 2.0, (b[1] + b[3]) / 2.0], dtype=float)
    return float(np.hypot(*(ca - cb)))


def match_frame(gt_objects: Sequence[GtObject], detections: Sequence[Detection],
                *, rule: str = "iou50", centre_tolerance_px: Optional[float] = None
                ) -> List[Tuple[int, int, float]]:
    """Greedy one-to-one matching of detections to GT objects in one frame.

    rule="iou50"       -> IoU >= 0.5
    rule="centre"      -> centre distance <= max(1 px, 0.5 * size_px) where
                          size_px = sqrt(w*h), i.e. half the equivalent side
                          (IoU is harsh for 4-6 px boxes: a 2 px shift on a 5x5 box
                          drops IoU to 0.43 and a 1 px shift on a 4x4 box to 0.39, so
                          a sub-pixel localisation is already a full miss.  The centre
                          rule is reported alongside and neither is called "the truth").
    Returns [(gt_index, det_index, score)].
    """
    if rule not in ("iou50", "centre"):
        raise ValueError("rule must be 'iou50' or 'centre', got " + repr(rule))
    order = sorted(range(len(detections)), key=lambda i: -detections[i].confidence)
    used_gt: set = set()
    matches: List[Tuple[int, int, float]] = []
    for det_index in order:
        det = detections[det_index]
        best = None
        best_score = -1.0
        for gt_index, obj in enumerate(gt_objects):
            if gt_index in used_gt:
                continue
            if rule == "iou50":
                score = iou_xyxy(obj.bbox_xyxy_px, det.bbox_xyxy_px)
                ok = score >= 0.5
            else:
                distance = centre_distance(obj.bbox_xyxy_px, det.bbox_xyxy_px)
                tolerance = centre_tolerance_px or max(1.0, 0.5 * max(obj.size_px, 1.0))
                score = 1.0 / (1.0 + distance)
                ok = distance <= tolerance
            if ok and score > best_score:
                best, best_score = gt_index, score
        if best is not None:
            used_gt.add(best)
            matches.append((best, det_index, best_score))
    return matches


def average_precision(confidences: Sequence[float], is_tp: Sequence[bool],
                      n_positive: int) -> Optional[float]:
    """All-point interpolated AP from a ranked list of detections in one bucket."""
    if n_positive <= 0 or not confidences:
        return None
    order = sorted(range(len(confidences)), key=lambda i: -confidences[i])
    tp_cum = 0
    fp_cum = 0
    points: List[Tuple[float, float]] = []
    for index in order:
        if is_tp[index]:
            tp_cum += 1
        else:
            fp_cum += 1
        points.append((tp_cum / n_positive, tp_cum / (tp_cum + fp_cum)))
    # all-point interpolation: precision envelope from the right
    best = 0.0
    envelope: List[Tuple[float, float]] = []
    for recall, precision in reversed(points):
        best = max(best, precision)
        envelope.append((recall, best))
    envelope.reverse()
    ap = 0.0
    previous_recall = 0.0
    for recall, precision in envelope:
        ap += (recall - previous_recall) * precision
        previous_recall = recall
    return float(ap)


def latency_stats(values: Sequence[Optional[float]]) -> Dict[str, Any]:
    """Descriptive latency statistics in milliseconds (None entries are dropped)."""
    clean = sorted(float(v) for v in values if v is not None and math.isfinite(float(v)))
    if not clean:
        return {"n": 0, "status": "NO_LATENCY_RECORDED"}

    def quantile(q: float) -> float:
        position = (len(clean) - 1) * q
        lo, hi = int(math.floor(position)), int(math.ceil(position))
        if lo == hi:
            return clean[lo]
        return clean[lo] + (clean[hi] - clean[lo]) * (position - lo)

    return {
        "n": len(clean),
        "mean_ms": round(float(sum(clean) / len(clean)), 4),
        "min_ms": round(clean[0], 4),
        "p50_ms": round(quantile(0.50), 4),
        "p90_ms": round(quantile(0.90), 4),
        "p95_ms": round(quantile(0.95), 4),
        "p99_ms": round(quantile(0.99), 4),
        "max_ms": round(clean[-1], 4),
        "note": "offline batch latency of the FIXTURE files, not camera-to-command latency",
    }


def _bucket_names() -> List[str]:
    return [name for name, _, _ in SIZE_BUCKET_EDGES] + [SMALLEST_BUCKET]


def evaluate(gt_path: Path, pred_path: Path, *, provenance: str,
             strict: bool = True, split: Optional[str] = None) -> Dict[str, Any]:
    """Run the P7-02/03 protocol end to end and return a JSON-safe report."""
    if provenance not in CLAIM_OF:
        raise ValueError("provenance must be one of " + repr(sorted(CLAIM_OF)))
    gt_raw = read_jsonl(Path(gt_path))
    pred_raw = read_jsonl(Path(pred_path))
    gt = parse_ground_truth(gt_raw, strict=strict)
    if split is not None:
        gt = {key: frame for key, frame in gt.items() if frame.split == split}
        if not gt:
            raise EvalSchemaError([("BAD_SCHEMA", f"{gt_path}", f"no ground-truth frame in split {split!r}")])
        for record in pred_raw:
            if record.get("frame_key") not in gt:
                raise EvalSchemaError([("UNKNOWN_FRAME", str(pred_path),
                                       f"prediction for frame {record.get('frame_key')!r} is outside split {split!r}")])
    detections = parse_predictions(pred_raw, strict=strict)
    counts = validate_inputs(gt, detections, strict=strict)

    by_frame: Dict[str, List[Detection]] = {}
    for det in detections:
        by_frame.setdefault(det.frame_key, []).append(det)

    report: Dict[str, Any] = {
        "schema": "badmin.p7.size_bucket_eval",
        "schema_version": 1,
        "claim": CLAIM_OF[provenance],
        "provenance": provenance,
        "real_detector_accuracy": False,
        "notes": [
            "No model was run by this harness; it only scores two JSONL files.",
            "This is NOT a real-detector accuracy claim, NOT a closed-loop result "
            "and NOT measured D455 data.",
        ],
        "detection_schema_source": SCHEMA_SOURCE,
        "p7_schema_module": P7_SCHEMA_MODULE,
        "inputs": {
            "ground_truth": {"path": str(gt_path), "records": len(gt_raw)},
            "predictions": {"path": str(pred_path), "records": len(pred_raw)},
        },
        "split": split or "ALL",
        "counts": counts,
        "bucket_edges": {name: [lo, None if math.isinf(hi) else hi]
                         for name, lo, hi in SIZE_BUCKET_EDGES},
        "buckets": {},
        "matching_rules": {},
        "latency": latency_stats([det.latency_ms for det in detections]),
    }

    for rule in ("iou50", "centre"):
        per_bucket: Dict[str, Any] = {}
        all_conf: List[float] = []
        all_tp: List[bool] = []
        ious: List[float] = []
        total_tp = total_fp = total_fn = 0
        for bucket in _bucket_names():
            bucket_gt = [obj for frame in gt.values() for obj in frame.objects
                         if obj.bucket == bucket]
            bucket_dets = [det for det in detections if det.bucket == bucket]
            matched_gt: set = set()
            matched_det: set = set()
            confidences: List[float] = []
            is_tp: List[bool] = []
            frame_iou: List[float] = []
            for frame_key, frame in gt.items():
                gt_in_bucket = [(index, obj) for index, obj in enumerate(frame.objects)
                                if obj.bucket == bucket]
                det_in_bucket = [det for det in by_frame.get(frame_key, [])
                                 if det.bucket == bucket]
                matches = match_frame([obj for _, obj in gt_in_bucket], det_in_bucket, rule=rule)
                for local_gt, det_index, _score in matches:
                    global_gt = gt_in_bucket[local_gt][0]
                    matched_gt.add((frame_key, global_gt))
                    det = det_in_bucket[det_index]
                    matched_det.add(id(det))
                    confidences.append(det.confidence)
                    is_tp.append(True)
                    frame_iou.append(iou_xyxy(frame.objects[global_gt].bbox_xyxy_px,
                                              det.bbox_xyxy_px))
                for det in det_in_bucket:
                    if id(det) not in matched_det:
                        confidences.append(det.confidence)
                        is_tp.append(False)
            n_gt = len(bucket_gt)
            n_tp = sum(1 for flag in is_tp if flag)
            n_fp = len(is_tp) - n_tp
            n_fn = n_gt - n_tp
            precision = (n_tp / (n_tp + n_fp)) if (n_tp + n_fp) else None
            recall = (n_tp / n_gt) if n_gt else None
            per_bucket[bucket] = {
                "gt_objects": n_gt,
                "detections": len(is_tp),
                "tp": n_tp,
                "fp": n_fp,
                "fn": n_fn,
                "precision": None if precision is None else round(precision, 4),
                "recall": None if recall is None else round(recall, 4),
                "ap": None if average_precision(confidences, is_tp, n_gt) is None
                else round(float(average_precision(confidences, is_tp, n_gt)), 4),
                "mean_iou": round(float(sum(frame_iou) / len(frame_iou)), 4) if frame_iou else None,
                "status": "NO_GT_OBJECTS" if n_gt == 0 else (
                    "NO_PREDICTIONS" if len(is_tp) == 0 else "SCORED"),
            }
            total_tp += n_tp
            total_fp += n_fp
            total_fn += n_fn
            all_conf.extend(confidences)
            all_tp.extend(is_tp)
            ious.extend(frame_iou)
        recall_all = total_tp / (total_tp + total_fn) if (total_tp + total_fn) else None
        report["matching_rules"][rule] = {
            "per_bucket": per_bucket,
            "overall": {
                "tp": total_tp, "fp": total_fp, "fn": total_fn,
                "precision": None if (total_tp + total_fp) == 0 else round(total_tp / (total_tp + total_fp), 4),
                "recall": None if recall_all is None else round(recall_all, 4),
                "ap": None if average_precision(all_conf, all_tp, total_tp + total_fn) is None
                else round(float(average_precision(all_conf, all_tp, total_tp + total_fn)), 4),
                "mean_iou": round(float(sum(ious) / len(ious)), 4) if ious else None,
            },
        }
    report["primary_matching_rule"] = "iou50"
    return report


def write_report(report: Mapping[str, Any], path: Path) -> Path:
    """Write the report deterministically (the evidence file is committed)."""
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
                   encoding="utf-8")
    return out
