# -*- coding: utf-8 -*-
"""P7-02 / P7-03: size-bucket offline evaluation protocol for shuttle detection.

Why this module exists
----------------------
The repo has accuracy reports (outputs/shuttle_capability/metrics/...) but they
were produced by ad-hoc scripts on a GPU host, from images that are not all
committed, and they do not share one protocol.  P7-02/P7-03 ask for something
smaller and stricter: one harness that consumes two JSONL files (predictions and
ground truth), VALIDATES both against a declared schema, and reports
precision / recall / AP per size bucket plus latency statistics.  No model is
run here.  If there are no prediction files, synthetic fixtures are used and the
result is stamped OFFLINE-SYNTHETIC.

What the stamps mean
--------------------
  OFFLINE-SYNTHETIC     inputs were generated by this repository; the numbers
                        measure the HARNESS, not a detector.
  OFFLINE-REAL-INPUTS   predictions came from a real run (paths recorded), but
                        nothing here is a closed loop and no frame was captured
                        by the robot.
Neither stamp is a real-detector-accuracy claim.  Every report carries
real_detector_accuracy=false and a note saying so; the tests assert this so a
future edit cannot quietly upgrade a synthetic number into a claim.

Input schema (one JSON object per line)
--------------------------------------
ground truth:
  {"schema": "badmin.p7.eval.ground_truth", "schema_version": 1,
   "frame_key": "cab_1_00000", "split": "val", "camera_id": "d455_left",
   "timestamp_s": 12.5, "image_size": {"width_px": 1280, "height_px": 720},
   "labeled": true,
   "objects": [{"bbox_xyxy_px": [100, 200, 106, 205], "size_px": 5.4}]}

predictions:
  {"schema": "badmin.p7.eval.predictions", "schema_version": 1,
   "frame_key": "cab_1_00000", "bbox_xyxy_px": [100.4, 200.2, 106.1, 205.3],
   "confidence": 0.62, "latency_ms": 21.5, "image_size": {...},
   "pixel_covariance": [[1.0,0.0],[0.0,1.0]], "camera_id": "d455_left",
   "timestamp_s": 12.5}

Rejections (EvalSchemaError, all listed, not just the first):
  * frame not labeled / labeled is not exactly true      -> UNLABELED_FRAME
  * prediction frame_key absent from the ground truth    -> UNKNOWN_FRAME
  * duplicate frame_key                                  -> DUPLICATE_FRAME
  * bbox not (4,), x2<=x1 or y2<=y1, negative coords     -> BAD_BBOX
  * NaN/Inf, confidence outside [0,1], latency < 0       -> BAD_NUMBER
  * camera_id / image_size disagreement with the GT frame-> MISMATCHED_FRAME
  * a metre-valued key in a pixel payload                -> UNIT_CONFUSION
  * unknown key (strict)                                 -> UNKNOWN_KEY

When the P7-04 detection schema module from PR #27 is importable it is used as
the authoritative per-detection validator (schema_source=P7_MODULE); otherwise a
compatibility validator implementing the same three pixel gates is used and
recorded as schema_source=FALLBACK_COMPAT.  The gate behaviour is tested
identically against both paths so merging PR #27 cannot change a verdict.

Run:
    python -m pytest tests/perception/shuttle_detection/test_size_bucket_eval.py -q
    python scripts/shuttle_detection/evaluate_size_buckets.py
"""
