# The four P7-02 buckets.  Edges are half-open [lo, hi) so a 6.0 px object lands
# in 6-10px; the convention is asserted in the tests.
SIZE_BUCKET_EDGES: Tuple[Tuple[str, float, float], ...] = (
    ("4-6px", 4.0, 6.0),
    ("6-10px", 6.0, 10.0),
    ("10-20px", 10.0, 20.0),
    (">20px", 20.0, math.inf),
)
SMALLEST_BUCKET = "<4px"
UNKNOWN_BUCKET = "unknown"

_METRIC_KEYS = ("bbox_xyxy_m", "position_m", "velocity_mps", "depth_m", "covariance_m2")
_GT_KEYS = ("schema", "schema_version", "frame_key", "split", "camera_id",
            "timestamp_s", "image_size", "labeled", "objects")
_PRED_KEYS = ("schema", "schema_version", "frame_key", "bbox_xyxy_px", "confidence",
              "latency_ms", "image_size", "pixel_covariance", "camera_id", "timestamp_s")
_OBJECT_KEYS = ("bbox_xyxy_px", "size_px")

