# -*- coding: utf-8 -*-
"""P6-03: D455 replay validator tests (good and bad synthetic fixtures).

The fixtures are generated by tools/p6_frames/make_d455_replay_fixtures.py and
declared OFFLINE-SYNTHETIC. The validator is expected to exit non-zero on every
violation, so the tests assert the exit code as well as the report content.
"""
from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.simulation.sensors import d455_metadata as md  # noqa: E402
from src.simulation.sensors import d455_replay as rp  # noqa: E402

FIX = ROOT / "tests/simulation/fixtures/p6_d455_replay"


def report_for(name: str, *, with_metadata: bool = True, **kwargs) -> rp.ReplayReport:
    meta = FIX / name / "metadata.json"
    return rp.validate_replay(
        FIX / name,
        metadata_path=meta if with_metadata and meta.is_file() else None,
        **kwargs,
    )


def codes(rep: rp.ReplayReport) -> set[str]:
    return {v.code for v in rep.violations}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# ------------------------------------------------------------------ passes --
def test_good_fixture_passes_with_exit_code_zero():
    rep = report_for("good")
    assert rep.violations == []
    assert rep.verdict == "PASS"
    assert rep.exit_code == 0
    assert rep.data_class == rp.DATA_CLASS_SYNTHETIC
    assert all(c.status != "FAIL" for c in rep.checks)


def test_report_is_machine_readable_and_says_no_calibration_is_claimed(tmp_path):
    rep = report_for("good")
    target = rep.write(tmp_path / "reports/good.json")
    payload = json.loads(target.read_text(encoding="utf-8"))
    assert payload["schema"] == rp.REPORT_SCHEMA
    assert payload["verdict"] == "PASS"
    assert payload["exit_code"] == 0
    assert payload["data_class"] == "OFFLINE-SYNTHETIC"
    assert payload["calibration_claimed"] is False
    for key in ("input", "thresholds", "counts", "metrics", "checks", "violations"):
        assert key in payload, key
    assert payload["metrics"]["max_dt_s"] == pytest.approx(1 / 30, rel=1e-6)
    assert payload["thresholds"]["monotonic_rule"].startswith("timestamps must be")


def test_every_check_carries_a_recognised_status():
    rep = report_for("good")
    ids = [c.id for c in rep.checks]
    assert len(ids) == len(set(ids))
    for check in rep.checks:
        assert check.status in ("PASS", "FAIL", "SKIP"), check


def test_external_witness_fixture_passes_the_real_data_pathway():
    rep = report_for("external_witness")
    assert rep.verdict == "PASS"
    assert rep.exit_code == 0
    assert rep.metrics["intrinsics"]["record_sha256"]


# -------------------------------------------------------------- violations --
def test_missing_depth_frame_is_caught_three_ways():
    rep = report_for("missing_frames")
    assert rep.verdict == "FAIL"
    assert rep.exit_code == 1
    assert {"MISSING_FRAME_FILE", "FRAME_COUNT_MISMATCH",
            "DIRECTORY_COUNT_MISMATCH"} <= codes(rep)
    assert rep.counts["rgb_files"] == 6
    assert rep.counts["depth_files"] == 5


def test_non_monotonic_timestamps_are_caught():
    rep = report_for("non_monotonic")
    assert rep.verdict == "FAIL"
    assert "NON_MONOTONIC_TIMESTAMP" in codes(rep)
    assert rep.metrics["min_dt_s"] <= 0.0


def test_gap_beyond_the_documented_threshold_is_caught():
    rep = report_for("gap")
    assert "TIMESTAMP_GAP_EXCEEDED" in codes(rep)
    assert rep.metrics["gap_threshold_s"] == pytest.approx(1.5 / 30, rel=1e-12)
    assert rep.metrics["max_dt_s"] == pytest.approx(0.5)


def test_gap_threshold_is_adjustable_but_documented():
    lenient = report_for("gap", max_gap_factor=20.0)
    assert "TIMESTAMP_GAP_EXCEEDED" not in codes(lenient)
    assert lenient.metrics["gap_threshold_s"] == pytest.approx(20.0 / 30.0)


def test_millimetre_depth_unit_is_caught():
    rep = report_for("mm_depth")
    assert "DEPTH_UNIT_NOT_METRES" in codes(rep)
    assert rep.verdict == "FAIL"


def test_millimetre_value_in_metres_field_is_caught_by_the_record():
    rep = report_for("mm_value_in_metres_field")
    assert codes(rep) == {"METADATA_INVALID"}
    assert "millimetres" in json.dumps(rep.to_dict())


def test_unknown_intrinsics_are_caught():
    rep = report_for("unknown_intrinsics")
    assert "INTRINSICS_UNKNOWN" in codes(rep)
    detail = " ".join(v.detail for v in rep.violations)
    assert "fx_px" in detail


def test_replay_alone_cannot_certify_intrinsics():
    rep = report_for("good", with_metadata=False)
    assert "INTRINSICS_UNKNOWN" in codes(rep)
    assert any("no metadata record" in v.detail for v in rep.violations)


def test_undeclared_alignment_flag_is_caught():
    rep = report_for("alignment_undeclared")
    assert "ALIGNMENT_UNKNOWN" in codes(rep)


def test_missing_fps_blocks_the_gap_check():
    rep = report_for("no_fps")
    assert "FPS_UNKNOWN" in codes(rep)
    gap_check = [c for c in rep.checks if c.id == "timestamp_gaps"][0]
    assert gap_check.status == "SKIP"


def test_bad_provenance_is_caught():
    rep = report_for("bad_sha")
    assert codes(rep) == {"METADATA_INVALID"}


def test_degree_fov_is_caught_at_the_record_layer():
    rep = report_for("deg_fov")
    assert codes(rep) == {"METADATA_INVALID"}


def test_missing_index_is_a_violation_not_a_crash(tmp_path):
    rep = rp.validate_replay(tmp_path / "no_such_dir")
    assert rep.verdict == "FAIL"
    assert codes(rep) == {"INDEX_MISSING"}
    assert rep.exit_code == 1


def test_absurd_gap_factor_is_refused():
    with pytest.raises(ValueError):
        rp.validate_replay(FIX / "good", max_gap_factor=0.0)
    with pytest.raises(ValueError):
        rp.validate_replay(FIX / "good", max_gap_factor=1e9)


def test_png_header_reader_refuses_a_non_png(tmp_path):
    assert rp.png_size(FIX / "good/rgb/000000.png") == (8, 6)
    bogus = tmp_path / "not.png"
    bogus.write_bytes(b"hello")
    with pytest.raises(ValueError) as exc:
        rp.png_size(bogus)
    assert "not a PNG" in str(exc.value)


# --------------------------------------------------------------------- CLI --
def run_cli(*args: str) -> subprocess.CompletedProcess:
    env = dict(os.environ)
    env["PYTHONPATH"] = str(ROOT)
    return subprocess.run(
        [sys.executable, "-m", "src.simulation.sensors.d455_replay", *args],
        cwd=str(ROOT),
        env=env,
        capture_output=True,
        text=True,
    )


def test_cli_exit_code_zero_on_the_good_fixture(tmp_path):
    report_path = tmp_path / "good_report.json"
    proc = run_cli(
        str(FIX / "good"),
        "--metadata",
        str(FIX / "good/metadata.json"),
        "--report",
        str(report_path),
    )
    assert proc.returncode == 0, proc.stderr
    assert "verdict=PASS" in proc.stdout
    payload = json.loads(report_path.read_text(encoding="utf-8"))
    assert payload["exit_code"] == 0


def test_cli_exit_code_one_on_a_bad_fixture(tmp_path):
    report_path = tmp_path / "mm_report.json"
    proc = run_cli(
        str(FIX / "mm_depth"),
        "--metadata",
        str(FIX / "mm_depth/metadata.json"),
        "--report",
        str(report_path),
        "--quiet",
    )
    assert proc.returncode == 1, proc.stdout
    payload = json.loads(report_path.read_text(encoding="utf-8"))
    assert payload["verdict"] == "FAIL"
    assert "DEPTH_UNIT_NOT_METRES" in {v["code"] for v in payload["violations"]}


def test_cli_exit_code_two_on_bad_usage():
    proc = run_cli(str(FIX / "good"), "--max-gap-factor", "0")
    assert proc.returncode == 2
    assert "usage/IO error" in proc.stderr


def test_cli_exit_code_one_on_a_missing_directory(tmp_path):
    proc = run_cli(str(tmp_path / "absent"), "--quiet")
    assert proc.returncode == 1
    assert "verdict=FAIL" in proc.stdout


# ---------------------------------------------------------------- fixtures --
def test_fixture_manifest_matches_the_files_on_disk():
    manifest = json.loads((FIX / "manifest.json").read_text(encoding="utf-8"))
    assert manifest["data_class"] == "OFFLINE-SYNTHETIC"
    files = manifest["files"]
    assert len(files) > 50
    for rel, digest in files.items():
        path = FIX / rel
        assert path.is_file(), rel
        assert sha256(path) == digest, rel


def test_fixture_generation_is_deterministic(tmp_path):
    sys.path.insert(0, str(ROOT / "tools/p6_frames"))
    import importlib

    gen = importlib.import_module("make_d455_replay_fixtures")
    rebuilt = gen.build(tmp_path / "rebuild")
    manifest = json.loads((FIX / "manifest.json").read_text(encoding="utf-8"))
    for rel, digest in manifest["files"].items():
        assert sha256(rebuilt / rel) == digest, rel


def test_fixtures_declare_themselves_synthetic():
    record = json.loads((FIX / "good/metadata.json").read_text(encoding="utf-8"))
    assert record["synthetic_fixture"]["is_real_d455_data"] is False
    assert "NOT A D455 MEASUREMENT" in record["synthetic_fixture"]["note"]
    unknown = json.loads((FIX / "unknown_intrinsics/metadata.json").read_text(
        encoding="utf-8"))
    assert unknown["synthetic_fixture"]["is_real_d455_data"] is False
    for name in ("good", "unknown_intrinsics", "mm_depth"):
        index = json.loads((FIX / name / "index.json").read_text(encoding="utf-8"))
        assert index["data_class"] == "OFFLINE-SYNTHETIC", name
